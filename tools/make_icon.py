#!/usr/bin/env python3
"""Make the Newton Extras-drawer icon (1-bit bitmap + mask) as NewtonScript.

    python3 tools/make_icon.py ../newton_os_on_the_iphone_by_2600rat_d204mz5-fullview.jpg > prelude/icon.ns

Needs Pillow. Draws the lightbulb in black; the mask is the bulb thickened by
a pixel so it stands out on the Extras drawer.

Newton bitmap binary layout (16-byte header, as in NTK-built packages):
4 bytes 0, rowBytes (2), 2 bytes 0, bounds top, left, bottom, right (2 each),
then rows of pixels, 1 = black.
"""
import sys
from PIL import Image, ImageChops, ImageFilter

SIZE = 28
ROWBYTES = 4


def bitmap(img):
    px = img.load()
    out = bytearray(4) + ROWBYTES.to_bytes(2, 'big') + bytes(2) + b''.join(v.to_bytes(2, 'big') for v in (0, 0, SIZE, SIZE))
    for y in range(SIZE):
        row = 0
        for x in range(ROWBYTES * 8):
            row = row << 1 | (1 if x < SIZE and px[x, y] else 0)
        out += row.to_bytes(ROWBYTES, 'big')
    return out.hex().upper()


def main():
    src = Image.open(sys.argv[1]).convert('RGB')
    bulb = src.crop((76, 118, 256, 298))          # lightbulb only, not the wordmark
    r, g, b = bulb.split()
    ink = ImageChops.lighter(ImageChops.lighter(r, g), b).point(lambda v: 255 if v > 60 else 0)
    ink = ink.filter(ImageFilter.MaxFilter(5))           # strokes survive the shrink
    small = ink.resize((SIZE, SIZE), Image.BOX).point(lambda v: 1 if v > 80 else 0)
    mask = small.point(lambda v: v * 255).filter(ImageFilter.MaxFilter(3)).point(lambda v: 1 if v else 0)
    print('// Generated by tools/make_icon.py -- do not edit by hand.')
    print('kAppIcon := {')
    print(f'    bits: MakeBinaryFromHex("{bitmap(small)}", \'bits),')
    print(f'    mask: MakeBinaryFromHex("{bitmap(mask)}", \'bits),')
    print(f'    bounds: {{left: 0, top: 0, right: {SIZE}, bottom: {SIZE}}}')
    print('};')


if __name__ == '__main__':
    main()
